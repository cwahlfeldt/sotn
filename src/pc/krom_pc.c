// tools/psyz/nugget/openbios/charset/font1.raw, which CMake turns into
// g_KromFont1 when it configures the build. Only the non-kanji block
// (0x8140-0x84BE: punctuation, full-width digits and Latin, kana) is there;
// the US version draws nothing else with it.
//
// SOTN_BIOS=<path to a 512 KiB PSX BIOS dump> uses that BIOS's own Kanji ROM
// instead. Its glyphs are narrower than openbios's, which matters to the
// menu, where text advances by each glyph's inked width.
