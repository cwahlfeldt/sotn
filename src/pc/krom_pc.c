// Reads one character of a UTF-8 string as its Shift-JIS code and moves
// *str past it. The PSX build runs its sources through iconv, so menu
// strings such as "Data saved．" reach DRA in Shift-JIS; PC sources stay
// UTF-8. *str must point at a lead byte (0xC0 or above). Characters the
// font lacks come back as 0x8140, a full-width space.
u16 PcUtf8ToSjis(const u8** str) {
    const u8* s = *str;
    u32 cp;
    s32 lo, hi, mid;

    if (s[0] >= 0xF0 && s[1] && s[2] && s[3]) {
        cp = ((s[0] & 7) << 18) | ((s[1] & 0x3F) << 12) | ((s[2] & 0x3F) << 6) |
             (s[3] & 0x3F);
        *str = s + 4;
    } else if (s[0] >= 0xE0 && s[1] && s[2]) {
        cp = ((s[0] & 0xF) << 12) | ((s[1] & 0x3F) << 6) | (s[2] & 0x3F);
        *str = s + 3;
    } else if (s[1]) {
        cp = ((s[0] & 0x1F) << 6) | (s[1] & 0x3F);
        *str = s + 2;
    } else {
        *str = s + 1;
        return 0x8140;
    }
    lo = 0;
    hi = LEN(sjis_table) - 1;
    while (lo <= hi) {
        mid = (lo + hi) / 2;
        if (sjis_table[mid][0] == cp) {
            return sjis_table[mid][1];
        }
        if (sjis_table[mid][0] < cp) {
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    }
    return 0x8140;
}
