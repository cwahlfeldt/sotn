static u32 KromOffset(u16 sjiscode) {
    u32 idx;

    for (idx = 1; krom_lookup[idx].codepoint <= sjiscode; idx++) {
    }
    idx--;
    return (sjiscode - krom_lookup[idx].codepoint + krom_lookup[idx].offset) *
           0x1E;
}

// Squeeze a glyph's inked columns to 85% of their width, OR-ing the columns
// that merge so no stroke is lost
static void NarrowGlyph(u8* g) {
    u16 rows[15], out[15];
    s32 x, y, t, a, b, w, tw;
    s32 l = 16, r = -1;

    for (y = 0; y < 15; y++) {
        rows[y] = g[y * 2] << 8 | g[y * 2 + 1];
        out[y] = 0;
        for (x = 0; x < 16; x++) {
            if (rows[y] & (0x8000 >> x)) {
                l = x < l ? x : l;
                r = x > r ? x : r;
            }
        }
    }
    if (r < 0) {
        return;
    }
    w = r - l + 1;
    tw = (w * 85 + 50) / 100;
    tw = tw < 1 ? 1 : tw;
    for (t = 0; t < tw; t++) {
        a = l + t * w / tw;
        b = l + (t + 1) * w / tw;
        b = b <= a ? a + 1 : b;
        for (y = 0; y < 15; y++) {
            for (x = a; x < b; x++) {
                if (rows[y] & (0x8000 >> x)) {
                    out[y] |= 0x8000 >> (l + t);
                }
            }
        }
    }
    for (y = 0; y < 15; y++) {
        g[y * 2] = out[y] >> 8;
        g[y * 2 + 1] = out[y];
    }
}

// openbios's Latin letters and digits are wider than the Kanji ROM's, and the
// game sized its text for Sony's: message boxes spilled into their next row
// ("Magically sealed" lost its M) and long menu descriptions their last
// letter. Narrow them in a copy of the font.
static const u8* KromNarrowLatin(void) {
    static const u16 ranges[][2] = {
        {0x824F, 0x8258}, {0x8260, 0x8279}, {0x8281, 0x829A}};
    u8* font = malloc(g_KromFont1Size);
    u32 i, offset;
    u16 ch;

    if (!font) {
        return g_KromFont1;
    }
    memcpy(font, g_KromFont1, g_KromFont1Size);
    for (i = 0; i < LEN(ranges); i++) {
        for (ch = ranges[i][0]; ch <= ranges[i][1]; ch++) {
            offset = KromOffset(ch);
            if (offset + 0x1E <= g_KromFont1Size) {
                NarrowGlyph(font + offset);
            }
        }
    }
    return font;
}

static void KromInit(void) {
    static u8* bios;
    const char* path = getenv("SOTN_BIOS");
    FILE* f;

    krom_lookup = krom_table;
    krom_font = KromNarrowLatin();
    krom_size = g_KromFont1Size;
    if (!path || !*path) {
        return;
    }
    bios = malloc(BIOS_SIZE);
    f = fopen(path, "rb");
    if (!bios || !f || fread(bios, 1, BIOS_SIZE, f) != BIOS_SIZE) {
        fprintf(stderr, "SOTN_BIOS: cannot read 512 KiB from %s\n", path);
        free(bios);
        bios = NULL;
    } else {
        krom_font = bios + BIOS_KROM;
        krom_size = BIOS_KROM_SIZE;
        krom_lookup = krom_bios_table;
    }
    if (f) {
        fclose(f);
    }
}

unsigned long Krom2RawAdd(unsigned short sjiscode) {
    u32 offset;

    if (!krom_font) {
        KromInit();
    }
    if (sjiscode < 0x8140 || sjiscode > 0x84BE) {
        return (unsigned long)-1;
    }
    offset = KromOffset(sjiscode);
    if (offset + 0x1E > krom_size) {
        return (unsigned long)-1;
    }
    return (unsigned long)&krom_font[offset];
}

